static void lba_to_chs(uint64_t lba, uint8_t *head, uint8_t *sector, uint8_t *cyl) {
    uint16_t sectors_per_track = 63;
    uint16_t heads = 255;
    
    *cyl = (uint8_t)(lba / (sectors_per_track * heads));
    *head = (uint8_t)((lba / sectors_per_track) % heads);
    *sector = (uint8_t)((lba % sectors_per_track) + 1);
}

int grub_create_partition_table(uint32_t disk_id, uint64_t disk_sectors) {
    struct mbr_header mbr;
    memset(&mbr, 0, sizeof(mbr));
    
    memcpy(mbr.bootstrap_code, grub_stage1_boot, sizeof(grub_stage1_boot));
    
    uint64_t boot_partition_start = 2048;
    uint64_t boot_partition_size = 1024 * 1024;
    
    uint64_t system_partition_start = boot_partition_start + boot_partition_size;
    uint64_t system_partition_size = disk_sectors - system_partition_start;
    
    mbr.partitions[0].boot_flag = PARTITION_FLAG_BOOTABLE;
    mbr.partitions[0].partition_type = PARTITION_TYPE_FAT32_LBA;
    mbr.partitions[0].start_lba = (uint32_t)boot_partition_start;
    mbr.partitions[0].total_sectors = (uint32_t)boot_partition_size;
    
    uint8_t start_head, start_sector, start_cyl;
    uint8_t end_head, end_sector, end_cyl;
    
    lba_to_chs(boot_partition_start, &start_head, &start_sector, &start_cyl);
    lba_to_chs(boot_partition_start + boot_partition_size - 1, &end_head, &end_sector, &end_cyl);
    
    mbr.partitions[0].start_head = start_head;
    mbr.partitions[0].start_sector_cyl_high = (start_sector & 0x3F) | ((start_cyl >> 2) & 0xC0);
    mbr.partitions[0].start_cyl_low = start_cyl & 0xFF;
    mbr.partitions[0].end_head = end_head;
    mbr.partitions[0].end_sector_cyl_high = (end_sector & 0x3F) | ((end_cyl >> 2) & 0xC0);
    mbr.partitions[0].end_cyl_low = end_cyl & 0xFF;
    
    mbr.partitions[1].boot_flag = 0x00;
    mbr.partitions[1].partition_type = PARTITION_TYPE_HVFS;
    mbr.partitions[1].start_lba = (uint32_t)system_partition_start;
    mbr.partitions[1].total_sectors = (uint32_t)system_partition_size;
    
    lba_to_chs(system_partition_start, &start_head, &start_sector, &start_cyl);
    lba_to_chs(system_partition_start + system_partition_size - 1, &end_head, &end_sector, &end_cyl);
    
    mbr.partitions[1].start_head = start_head;
    mbr.partitions[1].start_sector_cyl_high = (start_sector & 0x3F) | ((start_cyl >> 2) & 0xC0);
    mbr.partitions[1].start_cyl_low = start_cyl & 0xFF;
    mbr.partitions[1].end_head = end_head;
    mbr.partitions[1].end_sector_cyl_high = (end_sector & 0x3F) | ((end_cyl >> 2) & 0xC0);
    mbr.partitions[1].end_cyl_low = end_cyl & 0xFF;
    
    mbr.signature[0] = MBR_SIGNATURE_0;
    mbr.signature[1] = MBR_SIGNATURE_1;
    
    if (ata_write_sector(disk_id, 0, &mbr) != ATA_SUCCESS) {
        klog_error(LOG_DRV, "Failed to write MBR to disk %d", disk_id);
        return -1;
    }
    
    klog_info(LOG_DRV, "MBR partition table created on disk %d", disk_id);
    return 0;
}

int grub_install_mbr(uint32_t disk_id) {
    struct mbr_header mbr;
    
    if (ata_read_sector(disk_id, 0, &mbr) != ATA_SUCCESS) {
        klog_error(LOG_DRV, "Failed to read MBR from disk %d", disk_id);
        return -1;
    }
    
    memcpy(mbr.bootstrap_code, grub_stage1_boot, sizeof(grub_stage1_boot));
    
    mbr.bootstrap_code[0x1B8] = (uint8_t)(disk_id & 0xFF);
    
    mbr.signature[0] = MBR_SIGNATURE_0;
    mbr.signature[1] = MBR_SIGNATURE_1;
    
    if (ata_write_sector(disk_id, 0, &mbr) != ATA_SUCCESS) {
        klog_error(LOG_DRV, "Failed to write boot code to disk %d", disk_id);
        return -1;
    }
    
    klog_info(LOG_DRV, "GRUB boot code installed to disk %d", disk_id);
    return 0;
}

int grub_write_boot_code(uint32_t disk_id) {
    return grub_install_mbr(disk_id);
}

