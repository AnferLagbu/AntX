int grub_get_boot_sector(uint32_t disk_id, void *buffer) {
    if (buffer == NULL) {
        return -1;
    }
    
    return ata_read_sector(disk_id, 0, buffer);
}

int grub_set_boot_sector(uint32_t disk_id, const void *buffer) {
    if (buffer == NULL) {
        return -1;
    }
    
    return ata_write_sector(disk_id, 0, buffer);
}

uint32_t grub_calculate_kernel_lba(uint32_t disk_id, uint32_t partition) {
    (void)disk_id;
    
    uint32_t base_lba = 2048;
    
    if (partition == 0) {
        return base_lba + 8;
    }
    
    return base_lba + partition * 2048 + 8;
}

